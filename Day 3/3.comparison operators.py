#comparison operator : two values are compared and the result is either true or false
a = 10
b = 10

#equal to (==): if two value are equal, output = True else False
print(a == b)

#not equal to (!=): if two value are not equal, output = True else False
print(a != b)

#greater than (>): if left value is greater than right value, output = True else False
print(a > b)

#less than (<): if left value is less than right value, output = True else False
print(a < b)

#greater than or equal to (>=): if a isgreater than or equal to b then outuput is True, else False

#less than or equal to (<=): if a is less than or equal to b then output is True, else False

